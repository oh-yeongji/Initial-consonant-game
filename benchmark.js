const WordSchema = new mongoose.Schema({
  word: { type: String, required: true, unique: true },
  exists: { type: Boolean, default: true },
});
const WordModel = mongoose.model("Word", WordSchema);

async function fetchFromExternalAPI(word) {
  return new Promise((resolve) => {
    setTimeout(() => {
      resolve(REAL_NOUNS.includes(word));
    }, 1400);
  });
}

async function fetchFromLocalCache(word) {
  const start = performance.now();
  const wordData = await WordModel.findOne({ word }).lean();
  const end = performance.now();
  return { exists: !!wordData, time: (end - start).toFixed(4) };
}

async function startApp() {
  try {
    await mongoose.connect("mongodb://localhost:27017/consonant_play");
    console.log("✅ MongoDB Connected");

    const count = await WordModel.countDocuments();
    if (count === 0) {
      console.log("📦 Initializing DB with REAL_NOUNS...");
      const wordDocs = REAL_NOUNS.map((w) => ({ word: w }));
      await WordModel.insertMany(wordDocs);
    }

    app.get("/benchmark-all", async (req, res) => {
      console.log("⏱️ 1,000개 단어 전수 검사 및 성능 분석 시작...");

      let totalApiTime = 0;
      let totalCacheTime = 0;
      let fastestCache = Infinity;
      let slowestCache = 0;

      for (const word of REAL_NOUNS) {
        const apiStart = performance.now();
        await fetchFromExternalAPI(word);
        const apiEnd = performance.now();
        totalApiTime += apiEnd - apiStart;

        const cacheStart = performance.now();
        await WordModel.findOne({ word }).lean();
        const cacheEnd = performance.now();

        const currentCacheTime = cacheEnd - cacheStart;
        totalCacheTime += currentCacheTime;

        if (currentCacheTime < fastestCache) fastestCache = currentCacheTime;
        if (currentCacheTime > slowestCache) slowestCache = currentCacheTime;
      }

      const avgApi = (totalApiTime / REAL_NOUNS.length).toFixed(2);
      const avgCache = (totalCacheTime / REAL_NOUNS.length).toFixed(4);
      const boost = (avgApi / avgCache).toFixed(0);

      const summary = {
        "Total Words": REAL_NOUNS.length,
        "AVG API Time": `${avgApi}ms`,
        "AVG Cache Time": `${avgCache}ms`,
        "Fastest Cache": `${fastestCache.toFixed(4)}ms`,
        "Slowest Cache": `${slowestCache.toFixed(4)}ms`,
        "Overall Boost": `${boost}x Faster`,
      };

      console.log("🏁 벤치마크 완료!");
      console.table([summary]);
      res.json(summary);
    });

    app.listen(PORT, () => {
      console.log(
        `🚀 Benchmark server running on http://localhost:${PORT}/benchmark?word=망치`,
      );
    });
  } catch (err) {
    console.error("❌ Setup Error:", err);
  }
}

startApp();
